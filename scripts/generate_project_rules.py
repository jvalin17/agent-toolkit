#!/usr/bin/env python3
"""Generate short project rules (AGENTS.md / host overlays) from host bootstrap.

Replaces the missing generate-project-rules.sh documented in docs/other-llms.md.

Usage:
  python3 scripts/generate_project_rules.py [--host HOST] [--project DIR]
  python3 scripts/generate_project_rules.py --cursor   # alias for --host cursor
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Dict, Optional

TOOLKIT_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLKIT_ROOT / "hooks"))

from host_config import load_host_config, render_bootstrap, resolve_host  # noqa: E402


def _write_agents(project_dir: Path, text: str) -> None:
    header = (
        "<!-- Generated by agent-toolkit generate_project_rules — keep short; "
        "pull skills via MCP get_skill / get_module -->\n\n"
    )
    (project_dir / "AGENTS.md").write_text(header + text, encoding="utf-8")


def _write_cursor_mdc(project_dir: Path, text: str) -> None:
    rules_dir = project_dir / ".cursor" / "rules"
    rules_dir.mkdir(parents=True, exist_ok=True)
    # Cap mdc body further for always-on rules
    body = text[:3500]
    content = (
        "---\n"
        "description: Agent Toolkit bootstrap (LLM-agnostic)\n"
        "alwaysApply: true\n"
        "---\n\n"
        f"{body}\n"
    )
    (rules_dir / "toolkit.mdc").write_text(content, encoding="utf-8")


def generate_for_project(
    project_dir: Path,
    host_id: Optional[str] = None,
    toolkit_root: Optional[Path] = None,
) -> Dict[str, Any]:
    root = toolkit_root or TOOLKIT_ROOT
    project_dir = Path(project_dir)
    project_dir.mkdir(parents=True, exist_ok=True)

    cfg = load_host_config(host_id) if host_id else resolve_host()
    # Force toolkit_root for bootstrap file reads
    text = render_bootstrap(cfg, toolkit_root=root)

    written = []
    targets = cfg.get("rules_targets") or ["AGENTS.md"]
    for target in targets:
        if target in ("AGENTS.md", "GEMINI.md"):
            path = project_dir / target
            header = (
                "<!-- Generated by agent-toolkit generate_project_rules -->\n\n"
            )
            path.write_text(header + text, encoding="utf-8")
            written.append(str(path))
        elif target.endswith("toolkit.mdc") or target == ".cursor/rules/toolkit.mdc":
            _write_cursor_mdc(project_dir, text)
            written.append(str(project_dir / ".cursor" / "rules" / "toolkit.mdc"))

    if "AGENTS.md" not in {Path(p).name for p in written}:
        _write_agents(project_dir, text)
        written.append(str(project_dir / "AGENTS.md"))

    return {"ok": True, "host": cfg.get("id"), "written": written, "chars": len(text)}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate short AGENTS.md / host rules")
    parser.add_argument("--host", default=None, help="Host id (cursor, gemini, …)")
    parser.add_argument("--cursor", action="store_true", help="Alias for --host cursor")
    parser.add_argument("--project", default=".", help="Project directory")
    parser.add_argument("--toolkit", default=str(TOOLKIT_ROOT), help="Toolkit root")
    args = parser.parse_args(argv)

    host_id = "cursor" if args.cursor else args.host
    result = generate_for_project(
        Path(args.project),
        host_id=host_id,
        toolkit_root=Path(args.toolkit),
    )
    print(f"Host: {result['host']}")
    for path in result["written"]:
        print(f"Wrote: {path}")
    print(f"Bootstrap chars: {result['chars']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
